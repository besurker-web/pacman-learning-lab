import { test,expect } from '@playwright/test';
test('idle dashboard, reload, focus, speed selection and backup restore never start gameplay',async({page})=> {
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.getByRole('button',{name:'Start Training',exact:true})).toBeEnabled();
  await expect(page.getByRole('status')).toHaveText('Ready — press Start Training');
  const status=()=>page.frames().find(f=>f.url().includes('/engine/index'))!.evaluate(()=> (window as any).PacLab.status());
  expect(await status()).toMatchObject({frames:0,decisions:0,score:0,ai:false,invincible:false});
  await page.selectOption('#speed','5');await page.selectOption('#speed','max');await page.selectOption('#speed','1');
  await page.evaluate(()=>{window.dispatchEvent(new Event('focus'));document.dispatchEvent(new Event('visibilitychange'));});
  expect((await status()).frames).toBe(0);
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Export backup'}).click();const backup=await download;
  const path=await backup.path();expect(path).not.toBeNull();
  await page.locator('#backup-file').setInputFiles(path!);await expect(page.getByRole('status')).toContainText('Backup restored');
  expect((await status()).frames).toBe(0);await expect(page.locator('#updates')).toHaveText('0');
  await page.reload();await expect(page.getByRole('status')).toContainText('Saved progress loaded');
  expect((await status()).frames).toBe(0);
  await page.getByRole('button',{name:'Reset Learning',exact:true}).click();await page.getByRole('button',{name:'Keep learning'}).click();
  await page.getByRole('button',{name:'Reset Learning',exact:true}).click();await page.getByRole('button',{name:'Delete and reset'}).click();
  await expect(page.getByRole('status')).toHaveText('Ready — press Start Training');
  expect((await status()).frames).toBe(0);
  await page.setViewportSize({width:390,height:844});
  const frame=page.frames().find(f=>f.url().includes('/engine/index'))!;
  await expect(frame.locator('#atlas')).toBeHidden();
  await expect.poll(()=>frame.locator('#canvas').evaluate(el=>el.getBoundingClientRect().right<=innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await expect(page.locator('#error')).toBeHidden();expect(errors).toEqual([]);
});
